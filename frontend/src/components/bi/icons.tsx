import {
  ChartArea,
  ChartBar,
  ChartBarDecreasing,
  ChartBarStacked,
  ChartColumn,
  ChartColumnIncreasing,
  ChartColumnStacked,
  ChartLine,
  ChartNoAxesCombined,
  ChartPie,
  ChartScatter,
  Donut,
  Gauge,
  Grid3x3,
  Hash,
  LayoutGrid,
  LucideProps,
  SlidersHorizontal,
  Table2,
  TableProperties,
  Target,
  TrendingUp,
} from "lucide-react";

const ICONS: Record<string, React.ComponentType<LucideProps>> = {
  bar: ChartColumn,
  stacked_bar: ChartColumnStacked,
  hbar: ChartBar,
  stacked_hbar: ChartBarStacked,
  line: ChartLine,
  area: ChartArea,
  stacked_area: ChartArea,
  bar_line: ChartNoAxesCombined,
  stacked_bar_line: ChartNoAxesCombined,
  pie: ChartPie,
  donut: Donut,
  value: Hash,
  table: Table2,
  waterfall: ChartColumnIncreasing,
  tornado: ChartBarDecreasing,
  treemap: LayoutGrid,
  scatter: ChartScatter,
  heatmap: Grid3x3,
  trend: TrendingUp,
  kpi: Target,
  gauge: Gauge,
  pivot: TableProperties,
  control: SlidersHorizontal,
};

export function ChartTypeIcon({ type, ...p }: { type: string } & LucideProps) {
  const I = ICONS[type] ?? ChartColumn;
  return <I {...p} />;
}
