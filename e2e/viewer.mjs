import { chromium } from "playwright";
const out = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1400, height: 880 } });
page.setDefaultTimeout(10000);
const errors = [];
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
const step = async (name, fn) => { try { await fn(); console.log("OK  ", name); } catch (e) { console.log("FAIL", name, e.message.split("\n")[0]); await page.screenshot({ path: `${out}/fail-${name.replace(/\W+/g, "_")}.png` }); } };
await page.goto("http://localhost:8080/");
await page.getByRole("button", { name: "Connection" }).first().click();
await page.locator(".type-card").filter({ has: page.locator(`span:text-is("MySQL")`) }).click();
const field = (l) => page.locator(".field", { has: page.locator(`label:text-is("${l}")`) }).locator("input").first();
await field("Connection Name").fill("M"); await field("Host").fill("127.0.0.1"); await field("Port").fill("33306"); await field("Password").fill("chloe");
await page.getByRole("button", { name: "Save" }).click();
await page.locator(".tree-row", { hasText: "M" }).first().dblclick();
await page.locator(".tree-row", { hasText: /^\s*shop\s*$/ }).dblclick();
await page.locator(".tree-row", { hasText: "Tables" }).first().click();
await step("cmd+T query table", async () => {
  await page.locator(".object-list tr", { hasText: "customers" }).first().click();
  await page.keyboard.press("Meta+t");
  await page.locator(".tab", { hasText: "Query" }).waitFor();
  await page.waitForTimeout(400);
  const txt = (await page.locator(".monaco-editor .view-lines").first().innerText()).replace(/ /g, " ");
  if (!txt.includes("SELECT * FROM customers;")) throw new Error("editor text: " + txt);
  await page.screenshot({ path: `${out}/v0-cmdt.png` });
});
await step("down arrow adds row", async () => {
  await page.locator(".tab", { hasText: "Objects" }).click();
  await page.locator(".object-list tr", { hasText: "orders" }).first().dblclick();
  await page.locator(".grid-cell", { hasText: "paid" }).waitFor();
  await page.locator(".grid-row").last().locator(".grid-cell").nth(2).click();
  await page.keyboard.press("ArrowDown");
  await page.waitForTimeout(200);
  if ((await page.locator(".grid-row.new").count()) !== 1) throw new Error("no new row");
  await page.keyboard.type("1");
  await page.keyboard.press("Enter");
  await page.waitForTimeout(200);
  await page.screenshot({ path: `${out}/v1-viewer.png` });
});
console.log(errors.length ? "ERRORS:\n" + errors.join("\n") : "no page errors");
await browser.close();
