import { chromium } from "playwright";
import { PG } from "./lib/db.mjs";
const out = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 800 } });
page.setDefaultTimeout(10000);
page.on("pageerror", (e) => console.log("PAGE ERROR", e.message));
await page.goto(process.env.BASE ?? "http://localhost:8080/");
const field = (l) => page.locator(".field", { has: page.locator(`label:text-is("${l}")`) }).locator("input").first();
await page.getByRole("button", { name: "Connection" }).first().click();
await page.locator(".type-card").filter({ has: page.locator(`span:text-is("PostgreSQL")`) }).click();
await field("Connection Name").fill("P"); await field("Host").fill("127.0.0.1"); await field("Port").fill(PG); await field("User Name").fill("postgres"); await field("Password").fill("chloe");
await page.getByRole("button", { name: "Save" }).click();
const conn = page.locator(".tree-row", { hasText: /^\s*Pg\s*P\s*$/ }).first();
await conn.dblclick();
await page.locator(".tree-row", { hasText: /^\s*postgres\s*$/ }).dblclick();
await page.locator(".tree-row", { hasText: /^\s*shop\s*$/ }).dblclick();
await page.locator(".tree-row", { hasText: /^\s*Tables\s*$/ }).dblclick();
await page.locator(".tree-row", { hasText: /^\s*products\s*$/ }).dblclick();
await page.locator(".tree-row", { hasText: /^\s*orders\s*$/ }).dblclick();
await page.keyboard.press("Meta+t");
await page.waitForTimeout(300);
const tabs = async () => (await page.locator(".tabbar .tab").allInnerTexts()).map((x) => x.trim());
console.log("tabs:", await tabs());
// collapse the connection, then reveal products
await conn.locator(".twisty").click();
console.log("tree collapsed rows:", await page.locator(".tree-row").count());
await page.locator(".tabbar .tab", { hasText: "products" }).click({ button: "right" });
console.log("menu:", (await page.locator(".context-menu .menu-item").allInnerTexts()).map((x) => x.replace(/\s+/g, " ").trim()));
await page.locator(".context-menu").getByText("Reveal in Navigation Pane").click();
await page.waitForTimeout(800);
console.log("selected row:", await page.locator(".tree-row.selected").innerText().catch(() => "none"));
await page.screenshot({ path: `${out}/t1.png` });
// close tabs to the right of products
await page.locator(".tabbar .tab", { hasText: "products" }).click({ button: "right" });
await page.locator(".context-menu").getByText("Close Tabs to the Right").click();
console.log("after close right:", await tabs());
await page.keyboard.press("Meta+t");
await page.waitForTimeout(200);
console.log("before close others:", await tabs());
await page.locator(".tabbar .tab", { hasText: "products" }).click({ button: "right" });
await page.locator(".context-menu").getByText("Close Other Tabs").click();
console.log("after close others:", await tabs());
await page.locator(".tabbar .tab", { hasText: "products" }).click({ button: "right" });
await page.locator(".context-menu").getByText("Close All").click();
console.log("after close all:", await tabs(), "active:", await page.locator(".tabbar .tab.active").innerText());
await browser.close();
