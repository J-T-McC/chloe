import { chromium } from "playwright";
const out = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1400, height: 860 } });
page.setDefaultTimeout(10000);
page.on("pageerror", (e) => console.log("PAGE ERROR", e.message));
await page.goto(process.env.BASE ?? "http://localhost:8080/");
const field = (l) => page.locator(".field", { has: page.locator(`label:text-is("${l}")`) }).locator("input").first();
await page.getByRole("button", { name: "Connection" }).first().click();
await page.locator(".type-card").filter({ has: page.locator(`span:text-is("MySQL")`) }).click();
await field("Connection Name").fill("M"); await field("Host").fill("127.0.0.1"); await field("Port").fill("33306"); await field("Password").fill("chloe");
await page.getByRole("button", { name: "Save" }).click();
await page.locator(".tree-row", { hasText: "M" }).first().dblclick();
await page.locator(".tree-row", { hasText: /^\s*shop\s*$/ }).dblclick();
const run = async (sql) => {
  await page.locator(".tree-row", { hasText: /^\s*shop\s*$/ }).click();
  await page.keyboard.press("Meta+t");
  await page.locator(".query-editor:visible .monaco-editor .view-lines").click();
  await page.keyboard.insertText(sql);
  await page.keyboard.press("Meta+r");
  await page.waitForTimeout(600);
  await page.locator(".tab.active .tab-close").click();
  await page.locator(".modal").getByRole("button", { name: "Don't Save" }).click();
};
await run("DROP USER IF EXISTS 'sp_u'@'%'; CREATE USER 'sp_u'@'%' IDENTIFIED BY 'Pw!12345'");
await page.locator(".tree-row", { hasText: /^\s*Tables\s*$/ }).first().dblclick();
const open = async () => {
  await page.locator(".tree-row", { hasText: /^\s*orders\s*$/ }).click({ button: "right" });
  await page.locator(".context-menu").getByText("Set Privileges…").click();
  await page.locator(".set-privs").waitFor();
  await page.waitForTimeout(500);
};
await open();
console.log("headers:", (await page.locator(".set-privs th").allInnerTexts()).join(" | "));
console.log("rows before:", await page.locator(".set-privs tbody tr").count());
await page.locator(".set-privs .combobox input").fill("sp_u");
await page.locator(".set-privs .combobox input").press("Enter");
await page.locator(".set-privs").getByRole("button", { name: "Add" }).click();
const r = page.locator(".set-privs tbody tr", { hasText: "sp_u@%" });
const col = async (name) => (await page.locator(".set-privs th").allInnerTexts()).indexOf(name);
await r.locator("td").nth(await col("SELECT")).locator("input").check();
await r.locator("td").nth(await col("UPDATE")).locator("input").check();
await page.screenshot({ path: `${out}/sp1.png` });
await page.locator(".set-privs").getByRole("button", { name: "OK", exact: true }).click();
await page.locator(".set-privs").waitFor({ state: "detached" });
await open();
console.log("rows after grant:", (await page.locator(".set-privs tbody tr").allInnerTexts()).map((x) => x.replace(/\s+/g, " ").trim()));
const checked = await page.locator(".set-privs tbody tr", { hasText: "sp_u@%" }).locator("input:checked").count();
console.log("sp_u checked boxes:", checked);
await page.locator(".set-privs tbody tr", { hasText: "sp_u@%" }).locator("button[title='Revoke everything']").click();
await page.locator(".set-privs").getByRole("button", { name: "OK", exact: true }).click();
await page.locator(".set-privs").waitFor({ state: "detached" });
await open();
console.log("rows after revoke:", await page.locator(".set-privs tbody tr", { hasText: "sp_u" }).count());
await page.keyboard.press("Escape");
await run("DROP USER 'sp_u'@'%'");
await browser.close();
