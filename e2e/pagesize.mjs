import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 800 } });
page.setDefaultTimeout(8000);
await page.goto("http://localhost:8080/");
const field = (l) => page.locator(".field", { has: page.locator(`label:text-is("${l}")`) }).locator("input").first();
await page.getByRole("button", { name: "Connection" }).first().click();
await page.locator(".type-card").filter({ has: page.locator(`span:text-is("SQLite")`) }).click();
await field("Database File").fill(process.env.LITE + "/big.db");
await page.getByRole("button", { name: "Save" }).click();
await page.locator(".tree-row", { hasText: /big$/ }).dblclick();
await page.locator(".tree-row", { hasText: /^\s*main\s*$/ }).dblclick();
await page.locator(".tree-row", { hasText: /^\s*Tables\s*$/ }).dblclick();
await page.locator(".tree-row", { hasText: /^\s*n\s*$/ }).dblclick();
await page.locator(".viewer .grid-cell").first().waitFor();
const status = () => page.locator(".viewer .statusbar").innerText().then((t) => t.replace(/\s+/g, " "));
console.log("before:", await status());
const sel = page.locator(".viewer .statusbar select");
console.log("options:", await sel.locator("option").allInnerTexts());
await sel.selectOption({ index: 0 });
await page.waitForTimeout(600);
console.log("after:", await status(), "| select:", await sel.inputValue(), "| sql:", await page.locator(".viewer .sql-preview").innerText());
await page.locator(".viewer .statusbar button").filter({ has: page.locator("svg.lucide-chevron-right") }).click();
await page.waitForTimeout(500);
console.log("page 2:", await status(), "| first id:", await page.locator(".viewer .grid-row").first().locator(".grid-cell").first().innerText());
await browser.close();
