package design

import (
	"strings"
	"testing"
)

func s(v string) *string { return &v }

func baseTable() Table {
	return Table{
		Database: "shop", Schema: "app", Name: "items", OrigName: "items",
		Columns: []Column{
			{Name: "id", OrigName: "id", Type: "int", AutoIncrement: true},
			{Name: "sku", OrigName: "sku", Type: "varchar", Length: "32"},
			{Name: "price", OrigName: "price", Type: "decimal", Length: "10", Scale: "2", Default: s("0")},
			{Name: "note", OrigName: "note", Type: "text", Nullable: true},
		},
		PrimaryKey: &PrimaryKey{Name: "items_pkey", Columns: []string{"id"}},
		Indexes:    []Index{{Name: "idx_sku", OrigName: "idx_sku", Columns: []IndexColumn{{Name: "sku"}}}},
	}
}

// joiner returns a helper that fails the test on error and joins the statements.
func joiner(t *testing.T) func([]string, error) string {
	return func(stmts []string, err error) string {
		t.Helper()
		if err != nil {
			t.Fatal(err)
		}
		return strings.Join(stmts, ";\n")
	}
}

func TestMySQLCreate(t *testing.T) {
	tb := baseTable()
	tb.Columns[1].Collation = "utf8mb4_bin"
	tb.ForeignKeys = []ForeignKey{{Name: "fk_x", Columns: []string{"sku"}, RefTable: "skus", RefColumns: []string{"code"}, OnDelete: "CASCADE"}}
	tb.Checks = []Check{{Name: "ck_price", Expr: "price >= 0"}}
	tb.Options = Options{Engine: "InnoDB", Charset: "utf8mb4"}
	tb.Comment = "it's items"
	got := joiner(t)(MySQL{}.Create(tb))
	for _, want := range []string{
		"CREATE TABLE `shop`.`items` (",
		"`id` int NOT NULL AUTO_INCREMENT",
		"`sku` varchar(32) COLLATE utf8mb4_bin NOT NULL",
		"`price` decimal(10,2) NOT NULL DEFAULT 0",
		"`note` text NULL",
		"PRIMARY KEY (`id`)",
		"INDEX `idx_sku` (`sku`)",
		"CONSTRAINT `fk_x` FOREIGN KEY (`sku`) REFERENCES `skus` (`code`) ON DELETE CASCADE",
		"CONSTRAINT `ck_price` CHECK (price >= 0)",
		"ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='it''s items'",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in\n%s", want, got)
		}
	}
}

func TestMySQLAlter(t *testing.T) {
	old := baseTable()
	nw := baseTable()
	// rename sku -> code, widen it, move note before price, add a column, drop nothing
	nw.Columns[1].Name, nw.Columns[1].Length = "code", "64"
	nw.Columns[2], nw.Columns[3] = nw.Columns[3], nw.Columns[2]
	nw.Columns = append(nw.Columns, Column{Name: "qty", Type: "int", Default: s("1")})
	nw.Indexes[0].Columns = []IndexColumn{{Name: "code"}}
	nw.PrimaryKey.Columns = []string{"id", "code"}
	got := joiner(t)(MySQL{}.Alter(old, nw))
	for _, want := range []string{
		"DROP INDEX `idx_sku`",
		"DROP PRIMARY KEY",
		"CHANGE COLUMN `sku` `code` varchar(64) NOT NULL",
		"MODIFY COLUMN `note` text NULL AFTER `code`",
		"ADD COLUMN `qty` int NOT NULL DEFAULT 1 AFTER `price`",
		"ADD PRIMARY KEY (`id`, `code`)",
		"ADD INDEX `idx_sku` (`code`)",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in\n%s", want, got)
		}
	}
	if strings.Contains(got, "`price` decimal") && !strings.Contains(got, "MODIFY COLUMN `price`") {
		t.Errorf("unexpected price change\n%s", got)
	}
	// Nothing changed -> nothing to do.
	if stmts, err := (MySQL{}).Alter(old, baseTable()); err != nil || len(stmts) != 0 {
		t.Fatalf("no-op alter produced %v %v", stmts, err)
	}
}

func TestMySQLTriggerRules(t *testing.T) {
	tb := baseTable()
	tb.Triggers = []Trigger{{Name: "t1", Timing: "BEFORE", Events: []string{"INSERT", "UPDATE"}, Body: "SET NEW.sku = UPPER(NEW.sku)"}}
	if _, err := (MySQL{}).Create(tb); err == nil {
		t.Fatal("expected error for multi-event MySQL trigger")
	}
	tb.Triggers[0].Events = []string{"INSERT"}
	got := joiner(t)(MySQL{}.Create(tb))
	if !strings.Contains(got, "CREATE TRIGGER `t1` BEFORE INSERT ON `shop`.`items` FOR EACH ROW SET NEW.sku = UPPER(NEW.sku)") {
		t.Fatal(got)
	}
}

func TestPostgresCreate(t *testing.T) {
	tb := baseTable()
	tb.Columns[0].AutoIncrement = false
	tb.Columns[0].Identity = "by default"
	tb.Columns[3].Comment = "free text"
	tb.Uniques = []Unique{{Name: "items_sku_key", Columns: []string{"sku"}}}
	tb.Indexes[0].Where = "sku <> ''"
	tb.Triggers = []Trigger{{Name: "trg", Timing: "BEFORE", Events: []string{"INSERT", "UPDATE"}, ForEachRow: true, Function: "app.touch"}}
	got := joiner(t)(Postgres{}.Create(tb))
	for _, want := range []string{
		"CREATE TABLE app.items (",
		"id int GENERATED BY DEFAULT AS IDENTITY NOT NULL",
		"price decimal(10,2) NOT NULL DEFAULT 0",
		"CONSTRAINT items_pkey PRIMARY KEY (id)",
		"CONSTRAINT items_sku_key UNIQUE (sku)",
		"CREATE INDEX idx_sku ON app.items (sku) WHERE sku <> ''",
		"COMMENT ON COLUMN app.items.note IS 'free text'",
		"CREATE TRIGGER trg BEFORE INSERT OR UPDATE ON app.items FOR EACH ROW EXECUTE FUNCTION app.touch()",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in\n%s", want, got)
		}
	}
	tb.Columns[1].Unsigned = true
	if _, err := (Postgres{}).Create(tb); err == nil {
		t.Fatal("expected MySQL-only option error")
	}
}

func TestPostgresAlter(t *testing.T) {
	old := baseTable()
	old.Columns[0].AutoIncrement = false
	nw := old
	nw.Columns = append([]Column(nil), old.Columns...)
	nw.Columns[1].Name = "code"
	nw.Columns[1].Length = "64"
	nw.Columns[2].Default = nil
	nw.Columns[3].Nullable = false
	nw.Columns[0].Identity = "always"
	nw.Indexes = []Index{{Name: "idx_code", OrigName: "idx_sku", Columns: []IndexColumn{{Name: "code", Desc: true}}}}
	nw.Comment = "items"
	got := joiner(t)(Postgres{}.Alter(old, nw))
	for _, want := range []string{
		"DROP INDEX app.idx_sku",
		"ALTER TABLE app.items RENAME COLUMN sku TO code",
		"ALTER TABLE app.items ALTER COLUMN code TYPE varchar(64) USING code::varchar(64)",
		"ALTER TABLE app.items ALTER COLUMN price DROP DEFAULT",
		"ALTER TABLE app.items ALTER COLUMN note SET NOT NULL",
		"ALTER TABLE app.items ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY",
		"CREATE INDEX idx_code ON app.items (code DESC)",
		"COMMENT ON TABLE app.items IS 'items'",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in\n%s", want, got)
		}
	}
	if ColumnOrderChanged(old, nw) {
		t.Fatal("order should be unchanged")
	}
}

func TestValidate(t *testing.T) {
	tb := baseTable()
	tb.PrimaryKey.Columns = []string{"nope"}
	if err := Validate(tb); err == nil || !strings.Contains(err.Error(), "nope") {
		t.Fatalf("got %v", err)
	}
	tb = baseTable()
	tb.Columns = append(tb.Columns, Column{Name: "id", Type: "int"})
	if err := Validate(tb); err == nil {
		t.Fatal("expected duplicate column error")
	}
}
